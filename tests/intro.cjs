    await phase(page,'approach'); await page.locator('.intro-world-image').evaluate(image=>image.decode());
    assert.equal(await page.locator('.intro-world-plane').evaluate(el=>getComputedStyle(el).transitionDuration),'0s','最初からズーム後の位置を表示する');
    const nearScale=await page.locator('.intro-world-plane').evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).a);
    await finishVisuals(page); await page.screenshot({path:path.join(output,'intro-approach-desktop.png')});
    assert.equal(await page.locator('.intro-advance').isVisible(),false);
    assert.equal(await page.locator('.intro-tap-label').textContent(),'');
    assert.equal(await page.locator('.intro-experience[data-phase="wide"]').count(),0);
    await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
    await page.clock.runFor(30000); await phase(page,'approach');
    await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'));});
    await page.clock.runFor(2001); await phase(page,'monitor'); await finishVisuals(page);
    const monitorScale=await page.locator('.intro-world-plane').evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).a);
    assert.ok(monitorScale/nearScale<1.15,'モニターへの接近は小さな移動に抑える');
    const cover=await page.locator('.intro-monitor-veil').evaluate(el=>{const r=el.getBoundingClientRect();return r.left<=0&&r.top<=0&&r.right>=innerWidth&&r.bottom>=innerHeight;});
