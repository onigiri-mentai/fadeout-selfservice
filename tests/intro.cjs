    await logo.evaluate(image=>image.decode());
    await page.locator('.intro-title-card h1').evaluate(el=>el.getAnimations().forEach(a=>{a.pause();a.currentTime=3000;}));
    const centered=await logo.evaluate(el=>{const r=el.getBoundingClientRect();return Math.abs(r.x+r.width/2-innerWidth/2)<2&&Math.abs(r.y+r.height/2-innerHeight/2)<2;});
    assert.equal(centered,true,'タイトルロゴを白い画面中央に表示する');
    assert.equal(await page.locator('.intro-advance').isVisible(),false);
    await page.screenshot({path:path.join(output,'intro-title-desktop.png')});
    await page.clock.runFor(60000); await phase(page,'title');
    const authButton=page.getByRole('button',{name:'認証する',exact:true});
    const bottomCentered=await authButton.evaluate(el=>{const r=el.getBoundingClientRect();return Math.abs(r.x+r.width/2-innerWidth/2)<2&&r.top>innerHeight*.7&&r.bottom<innerHeight;});
    assert.equal(bottomCentered,true,'認証するを中央下部に置く');
    await authButton.focus(); await page.keyboard.press('Enter'); await phase(page,'authenticating');
    assert.equal(await page.locator('.intro-auth-spinner').isVisible(),true);
    assert.equal(await page.locator('.intro-auth-status').getAttribute('aria-busy'),'true');
    assert.equal(await page.locator('.intro-auth-spinner').evaluate(el=>getComputedStyle(el).animationName),'intro-auth-spin');
    await page.locator('[data-intro-action="authenticate"]').dispatchEvent('click');
    await page.screenshot({path:path.join(output,'intro-authenticating-desktop.png')});
    await page.clock.runFor(2001); await phase(page,'authenticated');
    assert.equal(await page.locator('.intro-auth-check').isVisible(),true);
    assert.equal(await page.locator('.intro-auth-spinner').isVisible(),false);
    assert.equal(await page.locator('#intro-auth-label').textContent(),'認証済み');
    await page.clock.runFor(60000); await phase(page,'authenticated');
    await page.reload();await enter(page); await phase(page,'authenticated');
    await page.screenshot({path:path.join(output,'intro-authenticated-desktop.png')});
    await page.getByRole('button',{name:'利用案内へ',exact:true}).focus(); await page.keyboard.press('Enter');
    await page.locator('#app[data-screen="guide"]').waitFor();
    for(const text of [...D.guide,...D.guideNotes]) await page.getByText(text,{exact:true}).waitFor();
    assert.equal(await page.locator('.masthead').isVisible(),false);
    await page.locator('#app').evaluate(el=>el.getAnimations().forEach(a=>a.finish()));
    await page.screenshot({path:path.join(output,'intro-guide-desktop.png'),fullPage:true});
    await page.locator('[data-action="accept-guide"]').click();
    await page.clock.runFor(60000); await page.locator('#app[data-screen="top"]').waitFor();
    await page.reload();await enter(page); await page.locator('#app[data-screen="top"]').waitFor();
    assert.equal(await page.locator('.intro-experience').count(),0,'再訪時は自動再開');
    await context.close();

    const mobile=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
    const phone=await mobile.newPage(); observe(phone); await phone.clock.install(); await phone.goto(URL);await enter(phone);
    for(let i=0;i<D.prologue.length;i++) await phone.locator('[data-intro-action="next"]').click({position:{x:30,y:400}});
    await phase(phone,'approach'); await phone.locator('.intro-world-image').evaluate(image=>image.decode());
    assert.equal(await phone.locator('.intro-experience').getAttribute('data-frame'),'portrait');
    assert.equal(await phone.locator('.intro-advance').isVisible(),false);
    assert.equal(await phone.locator('.intro-world-plane').evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
    await phone.screenshot({path:path.join(output,'intro-approach-mobile.png')});
    await phone.reload();await enter(phone); await phase(phone,'approach');
    await phone.locator('[data-intro-action="skip"]').click(); await phone.locator('#app[data-screen="guide"]').waitFor();
    assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await phone.screenshot({path:path.join(output,'intro-guide-mobile.png'),fullPage:true});
    await phone.locator('[data-action="accept-guide"]').click();
    await phone.locator('[data-action="history"]').click(); await phone.locator('[data-index="0"]').click(); await phone.locator('[data-action="read-memory"]').click();await continuePresent(phone);
    await phone.locator('.hotspot[data-id="chair"]').click();
    const before=await phone.evaluate(()=>JSON.parse(localStorage.getItem('fadeout.prototype.v1')));
