    // 旧版の遠景で保存されていても、新しい接近済みの構図から再開する。
    const oldIntro=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
    const checkpoint=E.fresh();checkpoint.started=true;checkpoint.introStage='wide';
    await oldIntro.addInitScript(value=>{if(!localStorage.getItem('fadeout.prototype.v1'))localStorage.setItem('fadeout.prototype.v1',value);},JSON.stringify(checkpoint));
    const resumed=await oldIntro.newPage();observe(resumed);await resumed.clock.install();await resumed.goto(URL);await enter(resumed);
