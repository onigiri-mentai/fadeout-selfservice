    await phone.locator('[data-action="replay-prologue"]').click(); await phase(phone,'prologue');
    await phone.locator('[data-intro-action="skip"]').click(); await phone.locator('[data-action="accept-guide"]').click();
    await phone.locator('#app[data-screen="memory"]').waitFor();
    const after=await phone.evaluate(()=>JSON.parse(localStorage.getItem('fadeout.prototype.v1')));
    assert.deepEqual(after.memories,before.memories,'冒頭の再生で調査履歴を消さない');
    await phone.setViewportSize({width:320,height:640});
    await phone.locator('[data-action="settings"]').click(); await phone.locator('[data-action="reset"]').click(); await phone.locator('#confirm-yes').click();
    await phase(phone,'prologue');
    for(let i=0;i<D.prologue.length;i++) await phone.locator('[data-intro-action="next"]').click({position:{x:30,y:400}});
    await phase(phone,'approach');
    await phone.clock.runFor(1601+1100); await phase(phone,'title');
    await phone.locator('.intro-title-card img').evaluate(image=>image.decode());
    const titleBounds=await phone.locator('.intro-title-card img').evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight;});
    assert.equal(titleBounds,true,'幅320pxでもロゴが切れない');
    await phone.screenshot({path:path.join(output,'intro-title-mobile.png')});
    assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await phone.getByRole('button',{name:'認証する',exact:true}).click(); await phase(phone,'authenticating');
    await phone.reload();await enter(phone); await phase(phone,'authenticating');
    await phone.clock.runFor(1601); await phase(phone,'authenticated');
    const menuFits=await phone.getByRole('button',{name:'利用案内へ',exact:true}).evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.bottom<=innerHeight;});
    assert.equal(menuFits,true,'幅320pxでも利用案内へが画面内に収まる');
    await phone.screenshot({path:path.join(output,'intro-authenticated-mobile.png')});
    await phone.getByRole('button',{name:'利用案内へ',exact:true}).click(); await phone.locator('#app[data-screen="guide"]').waitFor();
    assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await mobile.close();

    const legacy=await browser.newContext({reducedMotion:'reduce'});
    assert.equal(D.prologue.at(-1),'そう思って、私はここに来た。');
    const old=E.fresh(); old.started=true; old.guideAccepted=true; old.route='history'; delete old.introStage; delete old.introLine;
    await legacy.addInitScript(value=>localStorage.setItem('fadeout.prototype.v1',value),JSON.stringify(old));
    const returning=await legacy.newPage(); observe(returning); await returning.goto(URL);await enter(returning);
