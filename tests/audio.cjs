const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const {enter}=require('./helpers.cjs');
const URL=process.env.GAME_URL||'http://127.0.0.1:8000';
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage']});
  const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  const page=await context.newPage(),errors=[],musicRequests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().includes('self_OP.mp3'))musicRequests.push(r.url());});
  await context.addInitScript(()=>{
    window.testTones=0;window.testGains=[];
    const Audio=window.AudioContext||window.webkitAudioContext;
    const oscillator=Audio.prototype.createOscillator,gain=Audio.prototype.createGain,media=Audio.prototype.createMediaElementSource;
    Audio.prototype.createOscillator=function(){window.testTones++;return oscillator.call(this);};
    Audio.prototype.createGain=function(){const node=gain.call(this);window.testGains.push(node);return node;};
    Audio.prototype.createMediaElementSource=function(element){window.testMusicContext=this;return media.call(this,element);};
  });
  const phase=name=>page.locator(`.intro-experience[data-phase="${name}"]`).waitFor();
  const playing=()=>page.waitForFunction(()=>{const m=document.getElementById('intro-bgm');return !m.paused&&m.currentTime>.05&&window.testMusicContext?.state==='running';});
  const audioState=()=>page.locator('#intro-bgm').evaluate(m=>({paused:m.paused,time:m.currentTime,loop:m.loop,src:m.currentSrc}));
  const hide=hidden=>page.evaluate(value=>{Object.defineProperty(document,'hidden',{configurable:true,value});document.dispatchEvent(new Event('visibilitychange'));},hidden);
  try {
    await page.goto(URL);await page.getByRole('heading',{name:'このゲームは音が鳴ります'}).waitFor();
    assert.equal(await page.locator('.intro-experience').count(),0,'音の案内はプロローグより前');
    assert.equal((await audioState()).paused,true);assert.equal(musicRequests.length,0,'選ぶまでは音源を読み込まず鳴らさない');
    await page.setViewportSize({width:320,height:640});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await fs.mkdir(path.join(__dirname,'../test-results'),{recursive:true});
    await page.screenshot({path:path.join(__dirname,'../test-results/sound-gate-mobile.png'),fullPage:true});
    await page.locator('#start-volume').fill('45');assert.equal(await page.locator('#start-volume-value').textContent(),'45%');
    await enter(page,true);await phase('prologue');
    assert.equal(await page.evaluate(()=>testGains[1].gain.value),0,'黒いプロローグ直後はBGMを出さない');
    await playing();await page.waitForFunction(()=>testGains[1].gain.value>.6);
    let m=await audioState();assert.equal(m.loop,true);assert.ok(m.src.endsWith('/assets/audio/self_OP.mp3'));
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('fadeout.prototype.v1')).settings.sound),true);
    const before=await page.evaluate(()=>testTones);
    await page.locator('[data-intro-action="next"]').click();await playing();
    assert.ok(await page.evaluate(()=>testTones)>before,'文章送りにも控えめな操作音');
    await page.locator('[data-intro-action="sound"]').click();assert.equal((await audioState()).paused,true);
    const silentTones=await page.evaluate(()=>testTones);
    await page.locator('[data-intro-action="motion"]').click();assert.equal(await page.evaluate(()=>testTones),silentTones,'ミュートなら操作音も鳴らない');
    await page.locator('[data-intro-action="sound"]').click();await playing();
    await hide(true);assert.equal((await audioState()).paused,true);
    const pausedAt=(await audioState()).time;await page.waitForTimeout(150);assert.equal((await audioState()).time,pausedAt);
    await hide(false);await playing();
    for(let i=0;i<3;i++) await page.locator('[data-intro-action="next"]').click();
    await phase('approach');await playing();await phase('title');await playing();
    // タイトルで待ち続けても曲が終わらずループする。
    await page.locator('#intro-bgm').evaluate(m=>{m.currentTime=m.duration-.15;});
    await page.waitForFunction(()=>{const m=document.getElementById('intro-bgm');return m.currentTime<2&&!m.paused;});
    await page.reload();await page.locator('#app[data-screen="sound"]').waitFor();
    assert.equal((await audioState()).paused,true,'再訪でも最初のタップ前には鳴らない');
    await enter(page,true);await phase('title');await playing();
    await page.getByRole('button',{name:'認証する',exact:true}).click();await phase('authenticating');
    assert.equal((await audioState()).paused,true);assert.equal((await audioState()).time,0,'認証ボタンで曲を止める');
    await phase('authenticated');
    await hide(true);await hide(false);assert.equal((await audioState()).paused,true,'認証後に曲を再開しない');
    await page.getByRole('button',{name:'利用案内へ',exact:true}).click();await page.locator('#app[data-screen="guide"]').waitFor();
    let count=await page.evaluate(()=>testTones);
    await page.locator('[data-action="accept-guide"]').click();await page.locator('#app[data-screen="top"]').waitFor();
    assert.ok(await page.evaluate(()=>testTones)>count,'端末の操作ボタンにも操作音');
    count=await page.evaluate(()=>testTones);await page.locator('[data-action="settings"]').click();assert.ok(await page.evaluate(()=>testTones)>count);
    count=await page.evaluate(()=>testTones);await page.getByRole('button',{name:'設定を閉じる'}).click();assert.ok(await page.evaluate(()=>testTones)>count,'閉じるボタンにも操作音');
    await page.locator('[data-action="settings"]').click();await page.locator('#volume-setting').fill('10');
    await page.waitForFunction(()=>Math.abs(window.testGains[0].gain.value-.1)<.002);
    await page.locator('[data-action="replay-prologue"]').click();await phase('prologue');await playing();await page.waitForFunction(()=>testGains[1].gain.value>.6);
    await page.locator('[data-intro-action="skip"]').click();assert.equal((await audioState()).paused,true,'スキップでも曲を止める');
    assert.deepEqual(errors,[]);
    const silent=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
    const off=await silent.newPage();let fetched=false;off.on('request',r=>{if(r.url().includes('self_OP.mp3'))fetched=true;});
    await off.goto(URL);await enter(off);await off.locator('.intro-experience[data-phase="prologue"]').waitFor();
    assert.equal(await off.locator('#intro-bgm').evaluate(m=>m.paused),true);assert.equal(fetched,false,'音なしならMP3をダウンロードしない');
    await silent.close();

    // 仮想時計で3秒の境界・文章送り・背景タブ・予約の取消を確認する。
    const timing=await context.newPage();await timing.addInitScript(()=>localStorage.clear());await timing.clock.install({time:new Date('2026-11-08T00:00:00Z')});await timing.clock.pauseAt(new Date('2026-11-08T00:00:01Z'));await timing.goto(URL);await enter(timing,true);
    await timing.waitForFunction(()=>document.getElementById('intro-bgm').readyState>=2);
    const level=()=>timing.evaluate(()=>testGains[1].gain.value);
    await timing.clock.runFor(1500);await timing.locator('[data-intro-action="next"]').click();
    await timing.clock.runFor(1499);assert.equal(await level(),0,'文章を送っても2999msでは無音');
    await timing.clock.runFor(1);assert.ok(Math.abs(await level()-.65)<.0001,'3000msでBGMを出す');
    assert.ok(await timing.locator('#intro-bgm').evaluate(m=>m.currentTime<.3),'準備中に進んだ位置ではなく、曲の先頭から');
    await timing.locator('[data-intro-action="skip"]').click();await timing.locator('[data-action="accept-guide"]').click();
    await timing.locator('[data-action="settings"]').click();await timing.locator('[data-action="replay-prologue"]').click();
    await timing.clock.runFor(1000);
    await timing.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
    await timing.clock.runFor(10000);assert.equal(await level(),0);
    await timing.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'));});
    await timing.clock.runFor(1999);assert.equal(await level(),0,'背景タブにいた時間は数えない');
    await timing.clock.runFor(1);assert.ok(Math.abs(await level()-.65)<.0001);
    await timing.locator('[data-intro-action="skip"]').click();await timing.locator('[data-action="accept-guide"]').click();
    await timing.locator('[data-action="settings"]').click();await timing.locator('[data-action="replay-prologue"]').click();
    await timing.locator('[data-intro-action="skip"]').click();await timing.clock.runFor(10000);
    assert.equal(await timing.locator('#intro-bgm').evaluate(m=>m.paused),true,'スキップ後に予約されたBGMが鳴らない');
    await timing.locator('[data-action="accept-guide"]').click();await timing.locator('[data-action="settings"]').click();await timing.locator('[data-action="replay-prologue"]').click();
    for(let i=0;i<4;i++)await timing.locator('[data-intro-action="next"]').click();
    await timing.clock.runFor(2701);await timing.locator('[data-intro-action="authenticate"]').click();await timing.clock.runFor(10000);
    assert.equal(await timing.locator('#intro-bgm').evaluate(m=>m.paused),true,'3秒前に認証しても、あとからBGMが鳴らない');
    await timing.close();
    console.log('Audio passed: 3-second audible start, silent gesture priming, no reset on paragraph change, timer pause/cancel, real MP3/loop, UI tones, mute/volume, title resume, stop on authenticate/skip, replay, silent play, 320px.');
  } finally {await context.close();await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
